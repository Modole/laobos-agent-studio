import fs from "node:fs";
import { registerHooks, syncBuiltinESMExports } from "node:module";
import path from "node:path";
import { pathToFileURL } from "node:url";

const proxyMarker = ".laobos-asar-client-proxy";

function isBarePackageSpecifier(specifier) {
  return !specifier.startsWith(".")
    && !specifier.startsWith("/")
    && !specifier.startsWith("file:")
    && !specifier.startsWith("node:")
    && !path.isAbsolute(specifier);
}

function isInside(directory, target) {
  const relative = path.relative(directory, target);
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

function packageNameOfSpecifier(specifier) {
  const segments = specifier.split("/");
  return specifier.startsWith("@")
    ? segments.slice(0, 2).join("/")
    : segments[0];
}

function clientExportOf(manifest) {
  const client = manifest.exports?.["./client"];
  if (typeof client === "string") return client;
  return typeof client?.default === "string" ? client.default : undefined;
}

export function cleanGeneratedFallback(directory) {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const child = path.join(directory, entry.name);
    // This directory is regenerated by dsh-app-boot. Links left by an older
    // installation can point at a now-virtual app.asar path. DSH sees the same
    // target string after an in-place update and otherwise keeps the dangling
    // link, causing the host process to exit before the web service starts.
    if (entry.isSymbolicLink()) {
      fs.rmSync(child, { recursive: true, force: true });
      continue;
    }
    if (!entry.isDirectory()) continue;
    if (fs.existsSync(path.join(child, proxyMarker))) {
      fs.rmSync(child, { recursive: true, force: true });
    } else {
      cleanGeneratedFallback(child);
    }
  }
}

function writeClientProxy(target, link, packageName) {
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(path.join(target, "package.json"), "utf8"));
  } catch {
    return;
  }
  const clientRelative = clientExportOf(manifest);
  if (manifest.dsh?.client?.platform !== "web" || !clientRelative) return;

  const clientSource = path.join(target, clientRelative);
  const clientDestination = path.join(link, clientRelative);
  fs.mkdirSync(path.dirname(clientDestination), { recursive: true });
  fs.writeFileSync(path.join(link, "package.json"), `${JSON.stringify(manifest)}\n`);
  fs.writeFileSync(clientDestination, fs.readFileSync(clientSource));
  if (fs.existsSync(`${clientSource}.map`)) {
    fs.writeFileSync(`${clientDestination}.map`, fs.readFileSync(`${clientSource}.map`));
  }
  fs.writeFileSync(path.join(link, proxyMarker), `${packageName}\n`);
}

const studioRoot = process.env.LAOBOS_STUDIO_ROOT;
const dshHome = process.env.DSH_HOME;

if (studioRoot?.endsWith(".asar") && dshHome) {
  const fallbackDirectory = path.resolve(dshHome, "profiles", "node_modules");
  const installationPackages = new Set();
  const originalSymlinkSync = fs.symlinkSync;
  cleanGeneratedFallback(fallbackDirectory);

  // DSH normally maintains filesystem links for its in-box packages. An ASAR
  // package is a virtual directory, so an operating-system link to its
  // contents is necessarily dangling. Replace only those generated links with
  // tiny browser-client proxies; host imports use the resolver hook below.
  fs.symlinkSync = function laobosSymlinkSync(target, link, type) {
    const resolvedLink = path.resolve(String(link));
    const resolvedTarget = path.resolve(String(target));
    if (
      isInside(fallbackDirectory, resolvedLink)
      && isInside(path.resolve(studioRoot), resolvedTarget)
    ) {
      const packageName = path.relative(fallbackDirectory, resolvedLink)
        .split(path.sep)
        .join("/");
      if (!packageName.startsWith("@laobos/")) {
        installationPackages.add(packageName);
        writeClientProxy(resolvedTarget, resolvedLink, packageName);
      }
      return undefined;
    }
    return originalSymlinkSync(target, link, type);
  };
  syncBuiltinESMExports();

  const installationParentUrl = pathToFileURL(
    path.join(studioRoot, "package.json"),
  ).href;
  registerHooks({
    resolve(specifier, context, nextResolve) {
      const packageName = isBarePackageSpecifier(specifier)
        ? packageNameOfSpecifier(specifier)
        : undefined;
      if (packageName && installationPackages.has(packageName)) {
        try {
          return nextResolve(specifier, {
            ...context,
            parentURL: installationParentUrl,
          });
        } catch {
          // Fall through to the caller's normal lookup and original error.
        }
      }
      try {
        return nextResolve(specifier, context);
      } catch (originalError) {
        if (!isBarePackageSpecifier(specifier)) throw originalError;
        try {
          return nextResolve(specifier, {
            ...context,
            parentURL: installationParentUrl,
          });
        } catch {
          throw originalError;
        }
      }
    },
  });
}
